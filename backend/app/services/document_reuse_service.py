"""Never ask a customer for the same document twice.

Two checklists, both built from the single list in document_requirements.py:

  * financing_checklist - the Bidii Credit documents. Anything already
    uploaded on the insurance application for the SAME quote is attached
    automatically (the logbook, ID and KRA PIN the customer just gave us),
    and the "insurance premium quote" is generated by us from the selected
    quote - the customer never has a file for that.
  * application_checklist - the insurance application's own documents.
    For a LOGGED-IN customer, identity documents (national ID, KRA PIN)
    from their earlier applications are reused.

Reuse copies the document's metadata into a new row pointing at the same
stored file - nothing is re-uploaded or duplicated in storage - and logs
an event so staff can see exactly where each file came from.

Security: a guest is identified only by a phone number, so cross-application
reuse of identity documents is allowed ONLY for an authenticated customer
whose id matches the application's customer. For everyone else only
documents tied to this exact quote are reused (they were uploaded in this
same journey). The customer is only ever told that a document is "on file"
- never shown its contents or filename.
"""

import hashlib
import logging
from collections import defaultdict
from datetime import datetime

from fastapi import HTTPException, status
from sqlalchemy import select
from sqlalchemy.ext.asyncio import AsyncSession

from app.core.storage import get_storage
from app.models.application import Application, ApplicationDocument, ApplicationEvent
from app.models.customer import Customer
from app.models.financing import FinancingApplication, FinancingDocument, FinancingEvent
from app.models.provider import InsuranceProvider
from app.models.quote import Quote, QuoteRequest
from app.services.document_requirements import (
    REUSABLE_ACROSS_APPLICATIONS,
    SYSTEM_PROVIDED_TYPES,
    DocumentSpec,
    financing_documents,
    insurance_documents,
)
from app.services.simple_pdf import render_text_pdf

logger = logging.getLogger("somosure.document_reuse")

SRC_INSURANCE = "Reused from insurance application"
SRC_EARLIER = "Reused from earlier application"
SRC_GENERATED = "Generated by Somosure"


def _source_from_notes(notes: str | None) -> str:
    if notes:
        if notes.startswith(SRC_INSURANCE):
            return "insurance_application"
        if notes.startswith(SRC_EARLIER):
            return "earlier_application"
        if notes.startswith(SRC_GENERATED):
            return "generated"
    return "uploaded"


def _item(spec: DocumentSpec, state: str, source: str | None = None) -> dict:
    return {
        "type": spec.type,
        "label": spec.label,
        "description": spec.description,
        "tips": list(spec.tips),
        "state": state,
        "source": source,
    }


def _pick_earliest(candidates: list[tuple[int, datetime, object, str]]):
    """The first-uploaded document wins; documents tied to this exact
    quote (priority 0) beat anything from elsewhere (priority 1)."""
    return min(candidates, key=lambda c: (c[0], c[1]))


def _money(value) -> str:
    return f"{value:,.2f}"


