async def application_checklist(
    db: AsyncSession, application_id: str, *, attach: bool, authed_customer_id: str | None = None
) -> dict:
    app = await db.get(Application, application_id)
    if not app:
        raise HTTPException(status.HTTP_404_NOT_FOUND, "Application not found")

    quote = await db.get(Quote, app.quote_id)
    request = await db.get(QuoteRequest, quote.quote_request_id) if quote else None
    category = request.category if request else "motor"
    specs = insurance_documents(category)

    async def own_docs() -> dict[str, ApplicationDocument]:
        rows = (
            await db.scalars(
                select(ApplicationDocument)
                .where(ApplicationDocument.application_id == app.id, ApplicationDocument.status != "rejected")
                .order_by(ApplicationDocument.uploaded_at.asc())
            )
        ).all()
        out: dict[str, ApplicationDocument] = {}
        for r in rows:
            out.setdefault(r.document_type, r)
        return out

    have = await own_docs()

    if attach and authed_customer_id and authed_customer_id == str(app.customer_id):
        wanted = {s.type for s in specs if s.type in REUSABLE_ACROSS_APPLICATIONS and s.type not in have}
        if wanted:
            found: dict[str, list[tuple[int, datetime, object, str]]] = defaultdict(list)
            earlier_apps = (
                await db.scalars(
                    select(Application).where(Application.customer_id == app.customer_id, Application.id != app.id)
                )
            ).all()
            app_ref = {a.id: a.reference for a in earlier_apps}
            if app_ref:
                for d in (
                    await db.scalars(
                        select(ApplicationDocument).where(
                            ApplicationDocument.application_id.in_(list(app_ref)),
                            ApplicationDocument.document_type.in_(wanted),
                            ApplicationDocument.status != "rejected",
                        )
                    )
                ).all():
                    found[d.document_type].append((1, d.uploaded_at, d, f"{SRC_EARLIER} {app_ref[d.application_id]}"))
            prev_fin = (
                await db.scalars(select(FinancingApplication).where(FinancingApplication.customer_id == app.customer_id))
            ).all()
            fin_ref = {f.id: f.reference for f in prev_fin}
            if fin_ref:
                for d in (
                    await db.scalars(
                        select(FinancingDocument).where(
                            FinancingDocument.financing_application_id.in_(list(fin_ref)),
                            FinancingDocument.document_type.in_(wanted),
                            FinancingDocument.status != "rejected",
                        )
                    )
                ).all():
                    found[d.document_type].append(
                        (1, d.uploaded_at, d, f"{SRC_EARLIER} {fin_ref[d.financing_application_id]}")
                    )

            added = False
            for spec in specs:
                options = found.get(spec.type)
                if spec.type not in wanted or not options:
                    continue
                _, _, src_doc, source = _pick_earliest(options)
                db.add(
                    ApplicationDocument(
                        application_id=app.id,
                        document_type=spec.type,
                        storage_path=src_doc.storage_path,
                        original_filename=src_doc.original_filename,
                        content_type=src_doc.content_type,
                        size_bytes=src_doc.size_bytes,
                        status=src_doc.status,
                        validation_notes=source[:500],
                        file_hash=getattr(src_doc, "file_hash", None),
                    )
                )
                db.add(
                    ApplicationEvent(
                        application_id=app.id,
                        event_type="document_reused",
                        notes=f"{spec.label} - {source[0].lower() + source[1:]}",
                    )
                )
                added = True
            if added:
                if app.status == "draft":
                    app.status = "documents_required"
                await db.commit()
                have = await own_docs()

    items, missing = [], []
    for spec in specs:
        doc = have.get(spec.type)
        if doc:
            items.append(_item(spec, "provided", _source_from_notes(doc.validation_notes)))
        else:
            items.append(_item(spec, "missing"))
            missing.append(spec.type)
    return {"items": items, "missing": missing, "complete": not missing}
